//! Reading a recipes checkout from disk.
//!
//! Layout (see docs/authoring.md):
//!
//! ```text
//! catalog.yaml                               name and categories
//! locales/<locale>.json                      category translations
//! recipes/<tier>/<id>/recipe.yaml            a recipe; <tier> is official or community
//! recipes/<tier>/<id>/templates/             its own Tera templates
//! recipes/<tier>/<id>/locales/<locale>.json  its translations
//! shared/                                    image-free templates any recipe can use
//! schema/                                    JSON schemas for the YAML files
//! ```
//!
//! A `resources[].template` of `shared/<path>` names `shared/<path>`; any
//! other path names a file in the recipe's own `templates/`. The name, as
//! written, is the template's key in the published bundle.

use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};
use serde_json::Value;
use tetra_recipe::verification::CatalogKind;

/// Locale the YAML files are written in. Its `<locale>.json` files are
/// generated by `extract` and are not published.
pub const SOURCE_LOCALE: &str = "en";

/// Translations keyed by locale, the source locale excluded.
pub type Locales = BTreeMap<String, Value>;

/// Where a recipe comes from: `recipes/<tier>/<id>/`, published as the
/// index entry's `catalog`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Tier {
    /// Vetted and/or maintained by Fyra Labs.
    Official,
    /// Contributed by third parties.
    Community,
}

impl Tier {
    /// In publishing order: when two tiers share an id, the first one wins.
    pub const ALL: [Self; 2] = [Self::Official, Self::Community];

    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Official => "official",
            Self::Community => "community",
        }
    }

    /// What tetra calls this tier in an install's `source.catalog`.
    #[must_use]
    pub const fn catalog_kind(self) -> CatalogKind {
        match self {
            Self::Official => CatalogKind::Official,
            Self::Community => CatalogKind::Community,
        }
    }
}

/// A loaded checkout. Loading only fails on unreadable or unparseable files;
/// everything else is left for [`crate::check`] to report.
#[derive(Debug, Clone)]
pub struct Repo {
    pub root: PathBuf,
    /// `catalog.yaml`, parsed.
    pub catalog: Value,
    /// Text of `locales/en.json`, if present.
    pub catalog_source_locale: Option<String>,
    pub catalog_locales: Locales,
    /// Sorted by id (byte order), then tier.
    pub recipes: Vec<Recipe>,
    /// Every file under `shared/`, as sorted `/`-separated paths relative to it.
    pub shared_files: Vec<String>,
    /// Whether the old top-level `templates/` directory still exists.
    pub legacy_templates_dir: bool,
    /// Directories under `recipes/` that aren't a tier.
    pub stray_dirs: Vec<String>,
}

/// Prefix of template names that refer to `shared/`.
pub const SHARED_PREFIX: &str = "shared/";

#[derive(Debug, Clone)]
pub struct Recipe {
    pub tier: Tier,
    /// The directory name, which must equal `recipe_id`.
    pub dir_name: String,
    /// `recipes/<tier>/<id>`, for messages.
    pub path: String,
    /// Exact text of `recipe.yaml`; hashed and published byte for byte.
    pub yaml: String,
    /// `recipe.yaml`, parsed loosely (for the schema and extraction).
    pub doc: Value,
    /// The templates `resources` reference, by name as written.
    pub templates: BTreeMap<String, String>,
    /// Every file under the recipe's own `templates/`, as sorted
    /// `/`-separated paths relative to it.
    pub template_files: Vec<String>,
    /// Referenced templates that don't exist.
    pub missing_templates: Vec<String>,
    /// Referenced template paths that aren't plain relative paths.
    pub invalid_templates: Vec<String>,
    /// Text of `locales/en.json`, if present.
    pub source_locale: Option<String>,
    pub locales: Locales,
}

impl Recipe {
    /// Directory of this recipe's locale files.
    #[must_use]
    pub fn locales_dir(&self, root: &Path) -> PathBuf {
        root.join(&self.path).join("locales")
    }

    /// Where a template name points, relative to the repository root, for
    /// messages: `shared/<path>` or `recipes/<tier>/<id>/templates/<path>`.
    #[must_use]
    pub fn template_display_path(&self, name: &str) -> String {
        if name.starts_with(SHARED_PREFIX) {
            name.to_owned()
        } else {
            format!("{}/templates/{name}", self.path)
        }
    }
}

impl Repo {
    pub fn load(root: impl Into<PathBuf>) -> Result<Self> {
        let root = root.into();
        let catalog = read_yaml(&root.join("catalog.yaml"))?;
        let (catalog_source_locale, catalog_locales) = read_locales(&root.join("locales"))?;
        let shared_files = list_files(&root.join("shared"))?;
        let legacy_templates_dir = root.join("templates").is_dir();

        let recipes_dir = root.join("recipes");
        let mut recipes = Vec::new();
        let mut stray_dirs = Vec::new();
        for name in subdirs(&recipes_dir)? {
            let Some(tier) = Tier::ALL.into_iter().find(|tier| tier.as_str() == name) else {
                stray_dirs.push(name);
                continue;
            };
            for dir_name in subdirs(&recipes_dir.join(&name))? {
                recipes.push(Recipe::load(&root, tier, dir_name)?);
            }
        }
        recipes.sort_by(|a, b| (&a.dir_name, a.tier).cmp(&(&b.dir_name, b.tier)));

        Ok(Self {
            root,
            catalog,
            catalog_source_locale,
            catalog_locales,
            recipes,
            shared_files,
            legacy_templates_dir,
            stray_dirs,
        })
    }
}

impl Recipe {
    fn load(root: &Path, tier: Tier, dir_name: String) -> Result<Self> {
        let path = format!("recipes/{}/{dir_name}", tier.as_str());
        let dir = root.join(&path);
        let yaml_path = dir.join("recipe.yaml");
        let yaml = fs::read_to_string(&yaml_path)
            .with_context(|| format!("failed to read {path}/recipe.yaml"))?;
        let doc =
            parse_yaml(&yaml).with_context(|| format!("failed to parse {path}/recipe.yaml"))?;

        let mut templates = BTreeMap::new();
        let mut missing_templates = Vec::new();
        let mut invalid_templates = Vec::new();
        let names: BTreeSet<&str> = doc
            .get("resources")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(|resource| resource.get("template")?.as_str())
            .collect();
        for name in names {
            if !is_plain_relative_path(name) {
                invalid_templates.push(name.to_owned());
                continue;
            }
            let file = name.strip_prefix(SHARED_PREFIX).map_or_else(
                || dir.join("templates").join(name),
                |shared| root.join("shared").join(shared),
            );
            if file.is_file() {
                let body = fs::read_to_string(&file)
                    .with_context(|| format!("failed to read {}", file.display()))?;
                templates.insert(name.to_owned(), body);
            } else {
                missing_templates.push(name.to_owned());
            }
        }

        let template_files = list_files(&dir.join("templates"))?;
        let (source_locale, locales) = read_locales(&dir.join("locales"))?;
        Ok(Self {
            tier,
            dir_name,
            path,
            yaml,
            doc,
            templates,
            template_files,
            missing_templates,
            invalid_templates,
            source_locale,
            locales,
        })
    }
}

/// Parse YAML into a JSON value, keeping mapping order.
pub fn parse_yaml(text: &str) -> Result<Value> {
    Ok(serde_norway::from_str(text)?)
}

fn read_yaml(path: &Path) -> Result<Value> {
    let text =
        fs::read_to_string(path).with_context(|| format!("failed to read {}", path.display()))?;
    parse_yaml(&text).with_context(|| format!("failed to parse {}", path.display()))
}

/// A relative path made only of normal components (no `.`, `..`, root or
/// empty segments), so it names a file under the directory it's joined to.
#[must_use]
pub fn is_plain_relative_path(path: &str) -> bool {
    !path.contains(['\\', '\0']) && path.split('/').all(|part| !matches!(part, "" | "." | ".."))
}

/// `(text of en.json, other locales parsed)` for the `<locale>.json` files in
/// `dir`. A missing directory has no locales.
fn read_locales(dir: &Path) -> Result<(Option<String>, Locales)> {
    let mut source = None;
    let mut locales = Locales::new();
    if !dir.is_dir() {
        return Ok((source, locales));
    }
    for entry in fs::read_dir(dir).with_context(|| format!("failed to list {}", dir.display()))? {
        let path = entry?.path();
        let Some(locale) = path
            .file_name()
            .and_then(|name| name.to_str())
            .and_then(|name| name.strip_suffix(".json"))
        else {
            continue;
        };
        let text = fs::read_to_string(&path)
            .with_context(|| format!("failed to read {}", path.display()))?;
        if locale == SOURCE_LOCALE {
            source = Some(text);
        } else {
            let value = serde_json::from_str(&text)
                .with_context(|| format!("failed to parse {}", path.display()))?;
            locales.insert(locale.to_owned(), value);
        }
    }
    Ok((source, locales))
}

/// Names of the directories in `dir`, sorted; none if it doesn't exist.
fn subdirs(dir: &Path) -> Result<Vec<String>> {
    let mut names = Vec::new();
    if !dir.is_dir() {
        return Ok(names);
    }
    for entry in fs::read_dir(dir).with_context(|| format!("failed to list {}", dir.display()))? {
        let entry = entry?;
        if entry.path().is_dir() {
            names.push(utf8_name(&entry.file_name(), dir)?);
        }
    }
    names.sort();
    Ok(names)
}

/// Every file under `dir`, as sorted `/`-separated relative paths; none if
/// it doesn't exist.
fn list_files(dir: &Path) -> Result<Vec<String>> {
    let mut files = Vec::new();
    if dir.is_dir() {
        walk(dir, "", &mut files)?;
    }
    files.sort();
    Ok(files)
}

fn walk(dir: &Path, prefix: &str, files: &mut Vec<String>) -> Result<()> {
    for entry in fs::read_dir(dir).with_context(|| format!("failed to list {}", dir.display()))? {
        let entry = entry?;
        let name = format!("{prefix}{}", utf8_name(&entry.file_name(), dir)?);
        if entry.path().is_dir() {
            walk(&entry.path(), &format!("{name}/"), files)?;
        } else {
            files.push(name);
        }
    }
    Ok(())
}

fn utf8_name(name: &std::ffi::OsStr, dir: &Path) -> Result<String> {
    name.to_str().map(str::to_owned).with_context(|| {
        format!(
            "{}: file name `{}` is not UTF-8",
            dir.display(),
            name.display()
        )
    })
}

#[cfg(test)]
mod tests {
    use super::is_plain_relative_path;

    #[test]
    fn template_paths_stay_under_templates() {
        for good in ["a.tera", "containers/a.container.tera", "a/b/c.tera"] {
            assert!(is_plain_relative_path(good), "{good}");
        }
        for bad in [
            "",
            "/etc/passwd",
            "../a.tera",
            "a/../../b",
            "./a.tera",
            "a//b",
            "a/",
            "a\\b",
            "..",
        ] {
            assert!(!is_plain_relative_path(bad), "{bad}");
        }
    }
}
